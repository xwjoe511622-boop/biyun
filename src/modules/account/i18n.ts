/** Page-scoped translator. Global messages remain available through the root-scope fallback. */
export function useAccountI18n() {
  return useI18n({ useScope: 'local', messages: accountMessages })
}

/**
 * Server/`ApiError` messages are shown verbatim except for our own `account.*` keys, which are
 * translated so no internal key ever reaches the UI.
 */
export function translateAccountMessage(t: (key: string) => string, message: string): string {
  return message.startsWith('account.') ? t(message) : message
}
