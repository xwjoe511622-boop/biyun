// Page-scoped translator. Global messages remain available through the root-scope fallback.
export function useAuthI18n() {
  return useI18n({ useScope: 'local', messages: authMessages })
}

// Server/`ApiError` messages are shown verbatim except for our own `auth.*` keys, which are
// translated so no internal key ever reaches the UI.
export function translateAuthMessage(t: (key: string) => string, message: string): string {
  return message.startsWith('auth.') ? t(message) : message
}
