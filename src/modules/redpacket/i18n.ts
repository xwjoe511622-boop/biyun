/** 业务码 → 文案键（末尾段），未收录的码原样展示服务端文本。 */
export const RED_PACKET_ERROR_KEYS: Record<string, string> = {
  '2081': 'closed',
  '2101': 'coinUnavailable',
  '2102': 'limit',
  '2103': 'dailyLimit',
  '2104': 'tooFrequent',
  '2105': 'notFound',
  '2106': 'expiredOrRefunded',
  '2107': 'claimedOut',
  '2108': 'cannotClaimSelf',
  '2109': 'frozen',
  '2110': 'conservation',
  '2111': 'accountRestricted',
  '2112': 'ipLimited',
  '2113': 'fundsConfirming',
  '10002': 'login',
  '4': 'noPermission',
  '5': 'param',
  '8': 'googleCode',
  '2000': 'capitalPword',
  '2001': 'capitalPwordUnset',
}

/** 已知业务码用本地文案；未知码原样安全展示服务端文本（纯文本，绝不 v-html）。 */
export function redPacketErrorMessage(
  code: string | number | null | undefined,
  t: (key: string) => string,
  serverMessage: string,
): string {
  const key = RED_PACKET_ERROR_KEYS[String(code ?? '')]
  if (key !== undefined) return t(`rp.err.${key}`)
  const text = serverMessage.trim()
  return text !== '' ? text : t('rp.common.unknownError')
}

/** 红包模块局部翻译器；未定义的键继续从全局 bundle 解析。 */
export function useRedPacketI18n() {
  return useI18n({ messages: RP_MESSAGES })
}
