let merged = false

export function ensureFuturesMessages(): void {
  if (merged) return
  merged = true
  i18n.global.mergeLocaleMessage('zh-CN', futuresMessages['zh-CN'])
  i18n.global.mergeLocaleMessage('en-US', futuresMessages['en-US'])
}

/** `useI18n()` with the futures messages available. */
export function useFuturesI18n() {
  ensureFuturesMessages()
  return useI18n()
}
