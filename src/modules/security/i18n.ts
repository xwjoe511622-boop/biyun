/** Page-scoped translator. Global messages remain available through the root-scope fallback. */
export function useSecurityI18n() {
  return useI18n({ useScope: 'local', messages: securityMessages })
}

/**
 * Server/`ApiError` messages are shown verbatim except for our own `security.*` keys, which are
 * translated so no internal key ever reaches the UI.
 */
export function translateSecurityMessage(t: (key: string) => string, message: string): string {
  return message.startsWith('security.') ? t(message) : message
}
