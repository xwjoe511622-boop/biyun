/**
 * Human message for a failed OTC call. The server message (already localised by `exchange-language`)
 * wins; a few codes get an actionable hint appended. Codes: OtcMessage.java (2000/2001/2055/2074).
 */
export function describeOtcError(t: (key: string) => string, error: unknown): string {
  const hint: Record<string, string> = {
    '2074': t('otc.errors.nickname'),
    '2055': t('otc.errors.kyc'),
    '2001': t('otc.errors.fundUnset'),
    '2000': t('otc.errors.fundWrong'),
  }
  if (isApiError(error)) {
    if (error.isTransportFailure || error.kind === 'parse' || (error.kind === 'http' && (error.status ?? 0) >= 500)) {
      return t('otc.serviceUnavailable')
    }
    const extra = hint[error.code]
    const message = error.message.trim()
    if (extra !== undefined && message !== '' && !/^[a-z0-9_.]+$/i.test(message)) return `${message} · ${extra}`
    return extra ?? (message !== '' ? message : t('otc.serviceUnavailable'))
  }
  return error instanceof Error && error.message !== '' ? error.message : t('otc.serviceUnavailable')
}
